import assert from "node:assert/strict";
import { applyJournalUpdate } from "../lib/journal-update.ts";
import { exampleJournal } from "../lib/demo.ts";
const initial=exampleJournal("2026-11-20"),original=structuredClone(initial);
const trade={...initial.trades[0],version:2,asset:"UPDATED"};
let data=applyJournalUpdate(initial,{action:"saveTrade",id:trade.id,version:1,trade}, {trade});
assert.equal(data.trades.length,initial.trades.length);assert.equal(data.trades.find(t=>t.id===trade.id).asset,"UPDATED");
assert.equal(data.accounts,initial.accounts);
const account={...initial.accounts[0],version:2,name:"Edited"};
data=applyJournalUpdate(data,{action:"saveAccount",id:account.id,version:1,account},{account});
assert.equal(data.trades.find(t=>t.id===trade.id).asset,"UPDATED");assert.equal(data.accounts[0].name,"Edited");
const review={followed:"Plan",repeat:"",change:""},action={action:"saveReview",week:"month:2026-11",scope:"all",version:0,review};
data=applyJournalUpdate(data,action,{version:1});data=applyJournalUpdate(data,{...action,version:1},{version:2});
assert.equal(data.reviews.length,1);assert.equal(data.reviews[0].version,2);
data={...data,captures:[{tradeId:trade.id,slot:"before",revision:"r1"}]};
data=applyJournalUpdate(data,{action:"deleteTrade",id:trade.id,version:2},{id:trade.id});
assert.equal(data.trades.length,initial.trades.length-1);assert.equal(data.captures.length,0);
assert.equal(applyJournalUpdate(initial,{action:"deleteTrade",id:trade.id,version:1},{id:"wrong"}),null);
assert.equal(applyJournalUpdate(initial,{action:"saveAccount",id:account.id,version:1,account},{}),null);
assert.deepEqual(initial,original,"La reconciliación no muta el estado anterior");
console.log("Reconciliación local: guardado, metadatos, revisiones, eliminación y referencias OK.");
