import assert from "node:assert/strict";
import { exampleJournal } from "../lib/demo.ts";
import { resultR } from "../lib/journal.ts";
import { summarize, equity } from "../lib/stats.ts";
const fixture=exampleJournal("2026-11-20"),base=fixture.trades[0],start=Date.parse("2026-11-20T12:00:00Z");
const values=[-1,2,0,-0.5,3,-4,1];
const trades=values.map((r,i)=>({...base,id:crypto.randomUUID(),openedAt:start+i*60000,closedAt:start+i*60000+1000,riskCents:100,pnlCents:r*100,feesCents:10,partials:[]}));
const s=summarize(trades,fixture.accounts);
const close=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-12,`${actual} != ${expected}`);
assert.equal(s.closed,7);assert.equal(s.win,3);assert.equal(s.loss,3);assert.equal(s.flat,1);
assert.equal(s.cash,50);close(s.totalR,.5);close(s.meanR,.5/7);close(s.winRate,3/7*100);
close(s.factor,600/550);close(s.factorR,6/5.5);assert.equal(s.drawdown,400);assert.equal(s.drawdownR,4);close(s.recoveryR,.125);
assert.equal(s.bestR,3);assert.equal(s.worstR,-4);assert.equal(s.meanWinR,2);close(s.meanLossR,-5.5/3);close(s.ratio,12/11);
assert.deepEqual(equity(trades,"r").map(p=>p.value),[0,-1,1,1,.5,3.5,-.5,.5]);
const runs=summarize([1,1,-1,-1,-1,1].map((r,i)=>({...trades[i],pnlCents:r*100})),fixture.accounts);
assert.equal(runs.winStreak,2);assert.equal(runs.lossStreak,3);
const partial=summarize([...trades,{...base,id:crypto.randomUUID(),pnlCents:null,riskCents:null,entry:null}],fixture.accounts);
assert.equal(partial.cash,null);assert.equal(partial.factor,null);assert.equal(partial.drawdown,null);assert.equal(partial.rCount,7);assert.equal(partial.unknownCount,1);
assert.equal(resultR({...base,pnlCents:100,riskCents:100,feesCents:10}),1,"El P&L ya es neto: no restar comisiones dos veces");
assert.equal(resultR({...base,direction:"short",entry:100,stop:105,exit:100,pnlCents:null,partials:[]}),0);
assert.equal(resultR({...base,entry:1e-308,stop:5e-309,exit:1e9,direction:"long",pnlCents:null,partials:[]}),null,"No propagar desbordamientos numéricos");
console.log("Estadísticas financieras: resultados, cobertura, factores, expectativa, curva, drawdown, recuperación, rachas, BE y costes OK.");
