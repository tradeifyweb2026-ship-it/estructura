import assert from "node:assert/strict";
import { dailyRisk, openRisk, accountRisks } from "../lib/risk.ts";
import { tradeSchema, dayKey } from "../lib/journal.ts";
const now=Date.parse("2026-11-20T18:00:00Z"), today=dayKey(now);
const base=tradeSchema.parse({accountId:null,setupId:null,asset:"TEST",direction:"long",openedAt:now-86400000,closedAt:now,entry:100,stop:95,target:null,exit:95,size:null,riskCents:1000,riskPercent:null,pnlCents:-1000,feesCents:null,partials:[],before:null,during:null,after:null,notes:[],grade:null,errors:[],checklist:[]});
const trade=(extra={})=>({...base,id:crypto.randomUUID(),version:1,...extra});
assert.equal(dailyRisk([trade()],today,2).status,"within");
assert.equal(dailyRisk([trade(),trade()],today,2).status,"reached");
assert.equal(dailyRisk([trade(),trade({pnlCents:null,entry:null})],today,2).status,"incomplete");
assert.equal(dailyRisk([trade()],today,2,false).status,"incomplete");
assert.equal(dailyRisk([],today,2).status,"no-activity");
assert.equal(dailyRisk([trade()],today,null).status,"unconfigured");
const estimated=dailyRisk([trade({pnlCents:null})],today,2);
assert.equal(estimated.estimated,1);assert.equal(estimated.total,-1);
const open=trade({closedAt:null,exit:null,pnlCents:null,currentStop:100,partials:[{price:110,percent:50,at:now,pnlCents:1000}]});
assert.equal(dailyRisk([open],today,2).total,1);
assert.equal(openRisk(open).remainingCents,0);
assert.equal(openRisk({...open,currentStop:95}).remainingCents,500);
assert.equal(openRisk({...open,riskCents:null}).remainingCents,null);
assert.equal(openRisk({...open,entry:null}).remainingR,null);
assert.equal(dailyRisk([{...open,partials:[{price:110,percent:50}]}],today,2).status,"incomplete");
const closed=trade({partials:[{price:110,percent:50,at:now-86400000,pnlCents:1000}],exit:95,pnlCents:500});
assert.equal(dailyRisk([closed],today,2).total,-0.5,"Excluir parciales de días anteriores del P&L diario");
assert.equal(openRisk(trade({direction:"short",stop:105,currentStop:105,closedAt:null,partials:[{price:90,percent:25}]})).remainingCents,750);
assert.equal(dailyRisk([trade({accountId:crypto.randomUUID()}),trade({accountId:crypto.randomUUID()})],today,2).total,-2);
assert.equal(dailyRisk([trade({closedAt:now-86400000,openedAt:now-2*86400000,partials:[{price:110,percent:50}]})],today,2).status,"no-activity","Parciales históricos sin fecha no afectan al día actual");
const account={id:crypto.randomUUID(),version:1,name:"Fixture",type:"Demo",currency:"USD",startingBalanceCents:10000,archived:false,riskLimits:{dailyLossR:1,simultaneousPercent:5,perTradePercent:1}};
const second={...account,id:crypto.randomUUID()};
const isolated=accountRisks([trade({accountId:account.id,pnlCents:-1000}),trade({accountId:second.id,pnlCents:5000})],[account,second],today,2);
assert.equal(isolated[0].daily.status,"reached");assert.equal(isolated[1].daily.status,"within");
const simultaneous=accountRisks([trade({accountId:account.id,closedAt:null,exit:null,pnlCents:null,riskPercent:2})],[account],today,2)[0];
assert.equal(simultaneous.simultaneousStatus,"reached");assert.equal(simultaneous.simultaneousPercent,10);assert.equal(simultaneous.aboveTradeLimit,1);
assert.equal(accountRisks([trade({accountId:account.id,closedAt:null,entry:null})],[account],today,2)[0].simultaneousStatus,"incomplete");
assert.equal(accountRisks([trade({accountId:account.id})],[account],today,2,false)[0].daily.status,"incomplete");
console.log("Riesgo: cobertura, parciales fechados, long/short, BE, cuentas y límites OK.");
