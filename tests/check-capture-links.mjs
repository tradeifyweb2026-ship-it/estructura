import assert from 'node:assert/strict';
import { captureLinkSchema, isDirectCaptureImage, tradeSchema } from '../lib/journal.ts';
import { exampleJournal } from '../lib/demo.ts';
import { exportTrades, previewImport } from '../lib/csv.ts';
import { buildReport } from '../lib/report.ts';
import { reportCsv } from '../lib/report-csv.ts';
import { reportHtml } from '../lib/report-html.ts';
import { reportXlsx } from '../lib/report-xlsx.ts';
import { backupJson } from '../lib/share.ts';
const links = { before: 'https://www.tradingview.com/x/test123/', after: 'https://s3.tradingview.com/snapshots/t/test123.png' };
for (const url of Object.values(links)) assert.equal(captureLinkSchema.safeParse(url).success, true);
for (const url of ['http://tradingview.com/x/a', 'javascript:alert(1)', 'data:image/png;base64,AAAA', 'https://evil.test/a', 'https://tradingview.com.evil.test/a', 'https://eviltradingview.com/a', 'https://fake.tradingview.com/a', 'https://user:password@tradingview.com/a', 'https://tradingview.com:8080/a', 'https://tradingview.com/a b', 'https://tradingview.com/<script>', 'https://tradingview.com/%3Cscript%3E', 'https://tradingview.com/a\nb', 'https://tradingview.com/' + 'a'.repeat(300), 'https://tradingview.com\\@evil.test/a']) assert.equal(captureLinkSchema.safeParse(url).success, false, url);
assert.equal(isDirectCaptureImage(links.before), false);
assert.equal(isDirectCaptureImage(links.after), true);
assert.equal(isDirectCaptureImage('https://s3.tradingview.com/snapshots/a.svg'), false);
const journal = exampleJournal('2026-11-16');
const trade = journal.trades.find(t => t.closedAt !== null);
assert.equal(tradeSchema.safeParse(trade).success, true, 'Trade antiguo sin enlaces');
trade.captureLinks = links;
assert.equal(tradeSchema.safeParse(trade).success, true);
const account = journal.accounts.find(a => a.id === trade.accountId);
const roundTrip = await previewImport(exportTrades([trade], journal), account);
assert.equal(roundTrip.invalid.length, 0);
assert.deepEqual(roundTrip.valid[0].trade.captureLinks, links);
const report = buildReport({ trades: [trade], journal, period: 'Prueba', account: account.name, assumedCurrency: account.currency, now: 1794864000000 });
for (const output of [reportCsv(report), reportHtml(report), new TextDecoder().decode(reportXlsx(report)), backupJson(journal, 1794864000000)]) for (const link of Object.values(links)) assert.ok(output.includes(link), 'Exportación conserva el enlace');
assert.ok(!reportHtml(report).includes('<img src="https://'), 'PDF no descarga capturas externas');
console.log('check-capture-links: validación hostil, compatibilidad antigua, CSV y exportaciones OK');
